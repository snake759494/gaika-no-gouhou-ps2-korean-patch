_cache = {}


def _img(i):
    if i not in _cache:
        import images, tim2
        d = images.load(i); _cache[i] = tim2.decode(d, tim2.parse(d)[0])[..., :3].astype(int)
    return _cache[i]


def _mask(i, b):
    a = _img(i)[b[1]:b[3], b[0]:b[2]].max(2)
    return a > np.median(a) + 45


def _fill(i, b):
    a = _img(i)[b[1]:b[3], b[0]:b[2]].reshape(-1, 3)
    a = a[(a.max(1) - a.min(1)) < 40]
    if len(a) < 5: return (200, 200, 200)
    l = a.max(1); sel = a[l >= np.percentile(l, 95)]
    return tuple(int(x) for x in np.median(sel, 0))


def _opt(i, b, al, h):
    return dict(font_name='pixel', erase='rowfill', align=al, height=h, fill=_fill(i, b), out_w=0)


def _build():
    out = {}
    for ref, b, t, al, h in COMMON:
        m0 = _mask(ref, b)
        for i in range(10, 31):
            m = _mask(i, b)
            u = (m0 | m).sum()
            if u and (m0 & m).sum() / u > 0.7:
                out.setdefault(i, []).append((b, t, _opt(i, b, al, h)))
    out[28] = [x for x in out.get(28, []) if x[1] != '탄수']
    out[29] = [x for x in out.get(29, []) if x[1] != '연료']
    for i, items in EXTRA.items():
        have = {b for b, t, o in out.get(i, [])}
        for it in items:
            b, t, al, h = it[:4]
            if b in have: continue
            o = _opt(i, b, al, h)
            if len(it) > 4: o['fill'] = it[4]
            out.setdefault(i, []).append((b, t, o))
    return out


